/**
 * NEXXI Studio annotator (CLI only).
 *
 * Adds editing keys to the Stitch shells without touching their visual output:
 *   data-nxr="region"            region root (one Customizer section per region)
 *   data-nxe="k1,k2"             direct text nodes of an element, in order
 *   data-nxi="key"               <img> source
 *   data-nxl="key"               <a> destination
 *   data-nxp="key"               <input> placeholder
 * and writes the field registry to inc/studio-fields.php.
 *
 * Usage (from the workspace root):
 *   docker run --rm -v "${PWD}/wp-content/themes/nexxi-kids:/theme" -w /theme wordpress:cli-php8.3 php tools/studio-annotate.php
 */
if ( PHP_SAPI !== 'cli' ) { exit( 1 ); }

$theme = dirname( __DIR__ );
$pages = $theme . '/assets/stitch/pages';

/** Region locators per page. */
$specs = array(
	'index'      => array(
		'home-hero'         => array( 'section', 1 ),
		'home-categories'   => array( 'section', 2 ),
		'home-flash'        => array( 'section', 3 ),
		'home-lookbook'     => array( 'section', 4 ),
		'home-bestsellers'  => array( 'section', 5 ),
		'footer-brand'      => array( 'after', '<footer', '<div class="lg:col-span-2 space-y-space-md">', 1 ),
		'footer-col-1'      => array( 'after', '<footer', '<div class="space-y-space-sm">', 1 ),
		'footer-col-2'      => array( 'after', '<footer', '<div class="space-y-space-sm">', 2 ),
		'footer-newsletter' => array( 'after', '<footer', '<div class="space-y-space-sm">', 3 ),
		'footer-bottom'     => array( 'after', '<footer', '<div class="pt-space-lg flex', 1 ),
	),
	'shop'       => array(
		'shop-hero'  => array( 'section', 1 ),
		'shop-trust' => array( 'section', 4 ),
	),
	'flash-sale' => array(
		'flash-hero'     => array( 'section', 1 ),
		'flash-steps'    => array( 'section', 2 ),
		'flash-vouchers' => array( 'section', 5 ),
		'flash-terms'    => array( 'section', 6 ),
		'flash-notify'   => array( 'section', 7 ),
	),
	'product'    => array(
		'pdp-features' => array( 'comment', '<!-- Micro Feature Cards' ),
		'pdp-services' => array( 'comment', '<!-- Boutique Service Commitments' ),
	),
	'login'      => array(
		'login-story' => array( 'comment', '<!-- LEFT COLUMN' ),
	),
);

/** data-nx hooks whose content stays static (only their href changes), so they remain editable. */
$keep_hooks = array( 'home-cta-shop', 'home-cta-account', 'home-cat-1', 'home-cat-2', 'home-cat-3', 'home-cat-4', 'home-lookbook-1', 'home-lookbook-2', 'shop-title', 'shop-intro' );
/** Decorative icons that are not worth an editing field. */
$skip_icons = array( 'star', 'star_half', 'arrow_forward', 'arrow_back', 'arrow_back_ios_new', 'arrow_forward_ios', 'chevron_right', 'chevron_left', 'east', 'west', 'north_east', 'expand_more', 'close', 'add', 'remove' );

$fields = array();
$report = array();

foreach ( $specs as $page => $regions ) {
	$file = "$pages/$page.html";
	$html = file_get_contents( $file );
	$html = preg_replace( '~ data-nx[rielp]="[^"]*"~', '', $html ); // Idempotent: drop earlier studio keys.
	$ops = array();
	foreach ( $regions as $region => $locator ) {
		$start = nx_find_region( $html, $locator );
		if ( null === $start ) { fwrite( STDERR, "!! $page/$region not found\n" ); continue; }
		$ops[] = array( nx_tag_name_end( $html, $start ), ' data-nxr="' . $region . '"' );
		$state = (object) array( 'region' => $region, 'n' => array( 't' => 0, 'i' => 0, 'l' => 0, 'p' => 0 ), 'dedupe' => array(), 'group' => '', 'keep' => $keep_hooks, 'icons' => $skip_icons, 'stack' => array() );
		nx_parse( $html, $start, $state, false, $ops, $fields );
		$report[] = sprintf( '%-12s %-18s t=%d i=%d l=%d p=%d', $page, $region, $state->n['t'], $state->n['i'], $state->n['l'], $state->n['p'] );
	}
	usort( $ops, static function ( $a, $b ) { return $b[0] <=> $a[0]; } );
	foreach ( $ops as $op ) { $html = substr( $html, 0, $op[0] ) . $op[1] . substr( $html, $op[0] ); }
	file_put_contents( $file, $html );
}

// Document order inside each region (keys keep their ids).
$order = array_flip( array_unique( array_column( $fields, 'r' ) ) );
uasort( $fields, static function ( $a, $b ) use ( $order ) { return array( $order[ $a['r'] ], $a['o'] ) <=> array( $order[ $b['r'] ], $b['o'] ); } );
foreach ( $fields as &$f ) { unset( $f['o'] ); }
unset( $f );
$out = "<?php\n/** Generated by tools/studio-annotate.php – do not edit by hand. */\nif ( ! defined( 'ABSPATH' ) ) { exit; }\nreturn " . var_export( $fields, true ) . ";\n";
file_put_contents( $theme . '/inc/studio-fields.php', $out );
echo implode( "\n", $report ), "\nFields: ", count( $fields ), "\n";

