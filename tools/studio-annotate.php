function nx_find_region( $html, array $loc ) {
	switch ( $loc[0] ) {
		case 'section':
			$offset = 0;
			for ( $i = 0; $i < $loc[1]; $i++ ) {
				$pos = strpos( $html, '<section', $offset );
				if ( false === $pos ) { return null; }
				$offset = $pos + 1;
			}
			return $pos;
		case 'after':
			$base = strpos( $html, $loc[1] );
			if ( false === $base ) { return null; }
			$offset = $base;
			for ( $i = 0; $i < $loc[3]; $i++ ) {
				$pos = strpos( $html, $loc[2], $offset );
				if ( false === $pos ) { return null; }
				$offset = $pos + 1;
			}
			return $pos;
		case 'comment':
			$pos = strpos( $html, $loc[1] );
			if ( false === $pos ) { return null; }
			$pos = strpos( $html, '-->', $pos );
			$next = strpos( $html, '<', $pos + 3 );
			return false === $next ? null : $next;
	}
	return null;
}

function nx_tag_name_end( $html, $start ) {
	preg_match( '~\G<[a-zA-Z][a-zA-Z0-9-]*~', $html, $m, 0, $start );
	return $start + strlen( $m[0] );
}

function nx_tag_end( $html, $start ) {
	$len = strlen( $html );
	$quote = '';
	for ( $i = $start + 1; $i < $len; $i++ ) {
		$c = $html[ $i ];
		if ( '' !== $quote ) { if ( $c === $quote ) { $quote = ''; } continue; }
		if ( '"' === $c || "'" === $c ) { $quote = $c; continue; }
		if ( '>' === $c ) { return $i + 1; }
	}
	return $len;
}

function nx_attr( $open, $name ) {
	return preg_match( '~\s' . preg_quote( $name, '~' ) . '="([^"]*)"~', $open, $m ) ? html_entity_decode( $m[1], ENT_QUOTES | ENT_HTML5, 'UTF-8' ) : null;
}

function nx_clean( $text ) {
	$text = html_entity_decode( $text, ENT_QUOTES | ENT_HTML5, 'UTF-8' );
	return trim( preg_replace( '~\s+~u', ' ', str_replace( "\xC2\xA0", ' ', $text ) ) );
}

function nx_key( $state, $type ) {
	return $state->region . '__' . $type . ( ++$state->n[ $type ] );
}

function nx_text_label( array $stack, $tag, $text ) {
	if ( ! preg_match( '~[\p{L}\p{N}]~u', $text ) ) { return 'Emoji trang trí'; }
	if ( in_array( 'button', $stack, true ) || 'button' === $tag ) { return 'Chữ trên nút'; }
	foreach ( array( 'h1' => 'Tiêu đề chính', 'h2' => 'Tiêu đề khu vực', 'h3' => 'Tiêu đề mục', 'h4' => 'Tiêu đề mục' ) as $h => $name ) {
		if ( $tag !== $h && in_array( $h, $stack, true ) ) { return $name . ' – phần tô màu'; }
	}
	switch ( $tag ) {
		case 'h1': return 'Tiêu đề chính';
		case 'h2': return 'Tiêu đề khu vực';
		case 'h3':
		case 'h4':
		case 'h5': return 'Tiêu đề mục';
		case 'p': return mb_strlen( $text ) > 45 ? 'Đoạn mô tả' : 'Dòng chữ';
		case 'a': return 'Chữ liên kết';
		case 'li': return 'Mục danh sách';
	}
	if ( in_array( 'a', $stack, true ) ) { return 'Chữ trên nút / liên kết'; }
	return mb_strlen( $text ) > 45 ? 'Dòng chữ' : 'Nhãn';
}

/**
 * Walk one element (starting at its "<") and every descendant.
 * Returns the offset right after the element.
 */
function nx_parse( $html, $start, $state, $skip, array &$ops, array &$fields ) {
	preg_match( '~\G<([a-zA-Z][a-zA-Z0-9-]*)~', $html, $m, 0, $start );
	$tag = strtolower( $m[1] );
	$open_end = nx_tag_end( $html, $start );
	$open = substr( $html, $start, $open_end - $start );
	$name_end = $start + strlen( $m[0] );

	$hook = nx_attr( $open, 'data-nx' );
	if ( null !== $hook && ! in_array( $hook, $state->keep, true ) ) { $skip = true; }
	$id = nx_attr( $open, 'id' );
	if ( $id && preg_match( '~(hour|min|sec|day|countdown|timer|^fs-|toast)~i', $id ) ) { $skip = true; }

	// Void elements.
	if ( in_array( $tag, array( 'img', 'input', 'br', 'hr', 'meta', 'link', 'source', 'wbr' ), true ) ) {
		if ( ! $skip && 'img' === $tag ) {
			$src = nx_attr( $open, 'src' );
			if ( $src && false === strpos( $src, 'logo.jpg' ) ) {
				$key = nx_key( $state, 'i' );
				$ops[] = array( $name_end, ' data-nxi="' . $key . '"' );
				$fields[ $key ] = array( 'r' => $state->region, 't' => 'image', 'd' => $src, 'l' => 'Ảnh', 'g' => $state->group, 'o' => $start );
			}
		}
		if ( ! $skip && 'input' === $tag && null !== nx_attr( $open, 'placeholder' ) ) {
			$key = nx_key( $state, 'p' );
			$ops[] = array( $name_end, ' data-nxp="' . $key . '"' );
			$fields[ $key ] = array( 'r' => $state->region, 't' => 'placeholder', 'd' => nx_attr( $open, 'placeholder' ), 'l' => 'Chữ gợi ý trong ô nhập', 'g' => $state->group, 'o' => $start );
		}
		return $open_end;
	}
	// Raw-text / foreign elements: skip their body.
	if ( in_array( $tag, array( 'script', 'style', 'svg', 'select', 'textarea', 'template' ), true ) ) {
		if ( preg_match( '~</' . $tag . '\s*>~i', $html, $c, PREG_OFFSET_CAPTURE, $open_end ) ) { return $c[0][1] + strlen( $c[0][0] ); }
		return strlen( $html );
	}

	$class = (string) nx_attr( $open, 'class' );
	$is_icon = false !== strpos( $class, 'material-symbols' );
	$state->stack[] = $tag;
	$texts = array();
	$link_key = null;
	if ( ! $skip && 'a' === $tag && null !== nx_attr( $open, 'href' ) ) {
		$link_key = nx_key( $state, 'l' );
		$link_group = $state->group;
		$ops[] = array( $name_end, ' data-nxl="' . $link_key . '"' );
	}

	$i = $open_end;
	$len = strlen( $html );
	$end = $len;
	while ( $i < $len ) {
		$lt = strpos( $html, '<', $i );
		if ( false === $lt ) { break; }
		if ( $lt > $i ) {
			$raw = substr( $html, $i, $lt - $i );
			if ( '' !== nx_clean( $raw ) ) { $texts[] = array( nx_clean( $raw ), $i ); }
		}
		if ( 0 === substr_compare( $html, '<!--', $lt, 4 ) ) {
			$close = strpos( $html, '-->', $lt );
			$comment = trim( substr( $html, $lt + 4, $close - $lt - 4 ) );
			if ( ! $skip && '' !== $comment ) { $state->group = $comment; }
			$i = $close + 3;
			continue;
		}
		if ( '/' === $html[ $lt + 1 ] ) {
			$end = nx_tag_end( $html, $lt );
			if ( ! preg_match( '~\G</' . preg_quote( $tag, '~' ) . '\b~i', $html, $x, 0, $lt ) ) {
				fwrite( STDERR, "!! {$state->region}: <$tag> closed by " . substr( $html, $lt, 12 ) . "\n" );
			}
			break;
		}
		$i = nx_parse( $html, $lt, $state, $skip, $ops, $fields );
	}
	array_pop( $state->stack );

	if ( ! $skip && $texts ) {
		$keys = array();
		foreach ( $texts as $item ) {
			list( $text, $text_pos ) = $item;
			if ( preg_match( '~^[\d\s:.,%+\-/₫đ]+$~u', $text ) ) { $keys[] = '-'; continue; } // Counters / numbers stay automatic.
			if ( $is_icon ) {
				if ( in_array( $text, $state->icons, true ) ) { $keys[] = '-'; continue; }
				$type = 'icon';
				$label = 'Biểu tượng';
			} else {
				$type = 'text';
				$label = nx_text_label( $state->stack, $tag, $text );
			}
			$dedupe = $type . '|' . $text;
			if ( isset( $state->dedupe[ $dedupe ] ) ) { $keys[] = $state->dedupe[ $dedupe ]; continue; }
			$key = nx_key( $state, 't' );
			$state->dedupe[ $dedupe ] = $key;
			$keys[] = $key;
			$fields[ $key ] = array( 'r' => $state->region, 't' => $type, 'd' => $text, 'l' => $label, 'g' => $state->group, 'o' => $text_pos );
		}
		if ( array_filter( $keys, static function ( $k ) { return '-' !== $k; } ) ) {
			$ops[] = array( $name_end, ' data-nxe="' . implode( ',', $keys ) . '"' );
		}
	}
	if ( $link_key ) {
		$plain = nx_clean( strip_tags( preg_replace( '~<span[^>]*material-symbols[^>]*>.*?</span>~s', '', substr( $html, $open_end, max( 0, $end - $open_end ) ) ) ) );
		$fields[ $link_key ] = array( 'r' => $state->region, 't' => 'link', 'd' => '', 'l' => 'Link khi bấm: ' . ( '' !== $plain ? '“' . mb_strimwidth( $plain, 0, 40, '…' ) . '”' : 'ảnh / thẻ' ), 'g' => $link_group, 'o' => $start );
	}
	return $end;
}
